-- DesireTech Service OS - email queue for Supabase + Google Apps Script sending.
-- Run once (Supabase SQL editor or `supabase db push`). Safe to re-run.

create extension if not exists pgcrypto;

create table if not exists public.email_queue (
  id                    uuid primary key default gen_random_uuid(),
  communication_id      uuid not null unique,            -- idempotency key, generated by the app per email
  client_id             text,                            -- app ids are text (localStorage), not uuids
  lead_id               text,
  recipient             text not null,
  subject               text not null,
  body                  text,                            -- cleared after a successful send
  status                text not null default 'pending'
                        check (status in ('pending','processing','sent','failed')),
  scheduled_at          timestamptz not null default now(),
  processing_started_at timestamptz,
  sent_at               timestamptz,
  sent_from             text,
  error                 text,                            -- safe message only, never secrets
  error_code            text,                            -- unavailable | timeout | auth | quota | send_failed | interrupted
  attempts              int not null default 0,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

create index if not exists email_queue_due_idx on public.email_queue (scheduled_at) where status = 'pending';
create index if not exists email_queue_window_idx on public.email_queue (processing_started_at) where status in ('processing','sent');

-- Only the Edge Functions (service role) may touch this table. No policies = anon/authenticated get nothing.
alter table public.email_queue enable row level security;
revoke all on public.email_queue from anon, authenticated;

-- Atomically move due 'pending' rows to 'processing' (SKIP LOCKED => two overlapping cron runs never claim the same row).
create or replace function public.claim_due_emails(p_limit int)
returns setof public.email_queue
language sql security definer set search_path = public as $$
  update public.email_queue q
     set status = 'processing', attempts = q.attempts + 1, processing_started_at = now(), updated_at = now()
   where q.id in (
     select id from public.email_queue
      where status = 'pending' and scheduled_at <= now()
      order by scheduled_at
      limit greatest(p_limit, 0)
      for update skip locked)
  returning q.*;
$$;
revoke all on function public.claim_due_emails(int) from public, anon, authenticated;
grant execute on function public.claim_due_emails(int) to service_role;
